-- 1. BẢNG QUẢN LÝ NGƯỜI THUÊ (TENANTS)
CREATE TABLE IF NOT EXISTS RPT_TENANTS (
    TENANT_ID           VARCHAR(50) PRIMARY KEY,
    TENANT_NAME         VARCHAR(255) NOT NULL,
    API_KEY_HASH        VARCHAR(255) NOT NULL,
    STATUS              VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL,
    MAX_CONCURRENT_JOBS INT DEFAULT 5 NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. BẢNG QUẢN LÝ KẾT NỐI CSDL ĐỘNG (DATASOURCES)
CREATE TABLE IF NOT EXISTS RPT_DATASOURCES (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATASOURCE_CODE     VARCHAR(50) NOT NULL,
    TENANT_ID           VARCHAR(50) NOT NULL,
    NAME                VARCHAR(255) NOT NULL,
    DB_TYPE             VARCHAR(30) NOT NULL,
    JDBC_URL            VARCHAR(500) NOT NULL,
    USERNAME            VARCHAR(100) NOT NULL,
    PASSWORD_ENCRYPTED  VARCHAR(500) NOT NULL,
    MAX_POOL_SIZE       INT DEFAULT 10 NOT NULL,
    IS_READ_ONLY        BOOLEAN DEFAULT TRUE NOT NULL,
    STATUS              VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_TENANT_DS UNIQUE (TENANT_ID, DATASOURCE_CODE),
    CONSTRAINT FK_DS_TENANT FOREIGN KEY (TENANT_ID) REFERENCES RPT_TENANTS(TENANT_ID)
);

-- 3. BẢNG QUẢN LÝ MẪU BÁO CÁO (TEMPLATES)
CREATE TABLE IF NOT EXISTS RPT_TEMPLATES (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TEMPLATE_CODE       VARCHAR(50) NOT NULL,
    TENANT_ID           VARCHAR(50) NOT NULL,
    DATASOURCE_CODE     VARCHAR(50) NOT NULL,
    TEMPLATE_NAME       VARCHAR(255) NOT NULL,
    MODE                VARCHAR(20) DEFAULT 'GUI' NOT NULL,
    STATUS              VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL,
    IS_PUBLIC           BOOLEAN DEFAULT FALSE NOT NULL,
    IS_SYSTEM           BOOLEAN DEFAULT FALSE NOT NULL,
    CONFIG_JSON         TEXT NOT NULL,
    TRANSFORM_JS        TEXT,
    ACCESS_COUNT        INT DEFAULT 0 NOT NULL,
    LAST_ACCESSED_AT    TIMESTAMP WITH TIME ZONE,
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE,
    CREATED_BY          VARCHAR(100),
    DELETED_AT          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT UQ_TENANT_TPL UNIQUE (TENANT_ID, TEMPLATE_CODE),
    CONSTRAINT FK_TPL_TENANT FOREIGN KEY (TENANT_ID) REFERENCES RPT_TENANTS(TENANT_ID)
);

CREATE INDEX IF NOT EXISTS IDX_RPT_TPL_TENANT_STATUS ON RPT_TEMPLATES (TENANT_ID, STATUS);

-- 4. BẢNG QUẢN LÝ TIẾN TRÌNH XUẤT FILE (EXPORT TASKS)
CREATE TABLE IF NOT EXISTS RPT_EXPORT_TASKS (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TASK_CODE           VARCHAR(50) NOT NULL UNIQUE,
    TENANT_ID           VARCHAR(50) NOT NULL,
    TEMPLATE_ID         BIGINT,
    FILE_NAME           VARCHAR(255) NOT NULL,
    FILE_PATH           VARCHAR(500) NOT NULL,
    FILE_SIZE_BYTES     BIGINT,
    ROW_COUNT           INT,
    STATUS              VARCHAR(20) DEFAULT 'PROCESSING' NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EXPIRES_AT          TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY          VARCHAR(100) NOT NULL,
    CONSTRAINT FK_EXP_TENANT FOREIGN KEY (TENANT_ID) REFERENCES RPT_TENANTS(TENANT_ID),
    CONSTRAINT FK_EXP_TEMPLATE FOREIGN KEY (TEMPLATE_ID) REFERENCES RPT_TEMPLATES(ID)
);

CREATE INDEX IF NOT EXISTS IDX_RPT_EXP_TENANT_EXPIRES ON RPT_EXPORT_TASKS (TENANT_ID, EXPIRES_AT, STATUS);

-- 5. BẢNG PHỤC VỤ SHEDLOCK
CREATE TABLE IF NOT EXISTS shedlock (
    name VARCHAR(64) NOT NULL,
    lock_until TIMESTAMP NOT NULL,
    locked_at TIMESTAMP NOT NULL,
    locked_by VARCHAR(255) NOT NULL,
    PRIMARY KEY (name)
);

